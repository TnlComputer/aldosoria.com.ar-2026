<section class="pres-seccion" id="stages">
  <h2>Los Stages de reprogramación</h2>
  <p>Los Stages son distintas configuraciones de motor y caja. Para todos es necesario usar combustibles de alto octanaje en nafta y diésel con bajo contenido de azufre.</p>

  <div class="pres-tarjetas">
    <div class="pres-tarjeta">
      <h3><span>Stage 1</span> · Solo software</h3>
      <p>Actualización del software para ganar potencia sin cambiar periféricos externos. Cambio de filtro de aire y escape opcional.</p>
    </div>
    <div class="pres-tarjeta">
      <h3><span>Stage 2</span> · Software + periféricos</h3>
      <ul>
        <li>Escape y salida de turbo (down pipe) con diámetros especificados</li>
        <li>Filtros de aire</li>
        <li>Cambio o anulación de catalizadores</li>
        <li>Intercooler, mangueras IC y DV, válvulas DV</li>
      </ul>
    </div>
    <div class="pres-tarjeta">
      <h3><span>Stage 3</span> · Preparación completa</h3>
      <ul>
        <li>Turbocargadores e inyectores</li>
        <li>Internos de motor: bielas, pistones, válvulas y resortes</li>
        <li>Múltiple de admisión y bomba de combustible de mayor caudal</li>
        <li>Sensores MAF y MAP, escape down pipe, intercooler</li>
        <li>Equipos de agua-metanol</li>
      </ul>
    </div>
    <div class="pres-tarjeta">
      <h3><span>Otras funciones</span></h3>
      <ul>
        <li>Launch Control, NCL, antilag y turbo lag en ME 7.5, MED9 y MED17</li>
        <li>Seteos de Multimap</li>
        <li>Cajas DSG del grupo VAG (Stage 1-2): Launch Control, RPM máxima y tiempo de cambio</li>
      </ul>
    </div>
  </div>
</section>

